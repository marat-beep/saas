select 'aaaaaaaa-0000-0000-0000-000000000001', v.category, v.question, v.answer, v.tags
from (values
  ('ЧПУ','Управляющие программы (УП): реестр, версии, отчёт',
   'УП (app_nc_list, app_nc_save): заказ, деталь, станок, номер, версия, время обработки (мин), статусы (черновик → апробирована → архив), файлы УП (AppFiles, entity ''nc''). KPI — app_nc_kpi (программ/апробировано/черновиков/суммарное время). Реестр УП — кнопка «📄 Отчёт PDF». Связи: Заказы, Маршруты (КД), Производство/MES, Пульт оператора.',
   'ЧПУ УП управляющая программа реестр версии время обработки отчёт')
) as v(category,question,answer,tags)
where not exists (
  select 1 from public.app_knowledge
   where tenant_id = 'aaaaaaaa-0000-0000-0000-000000000001' and question = 'Управляющие программы (УП): реестр, версии, отчёт'
