-- ================= Исправление поиска базы знаний =================
create or replace function public.app_kb_search(p_token uuid, p_query text)
returns table (id uuid, category text, question text, answer text)
language plpgsql security definer set search_path = public
as $$
#variable_conflict use_column
declare urole text; ten uuid; q text; toks text[];
begin
  if not public.app_production_allowed(p_token) then raise exception 'Доступ запрещён'; end if;
  select s.urole into urole from public.app_session_user(p_token) s;
  ten := public.app_my_tenant(p_token);
  q := lower(coalesce(trim(p_query),''));
  if q = '' then
    return query select k.id, k.category, k.question, k.answer
      from public.app_knowledge k
     where (urole='admin' or k.tenant_id = ten or k.tenant_id is null)
     order by k.created_at desc limit 20;
    return;
  end if;
  toks := string_to_array(q, ' ');
  return query
    select k.id, k.category, k.question, k.answer
      from public.app_knowledge k
     where (urole='admin' or k.tenant_id = ten or k.tenant_id is null)
       and (
         k.question ilike '%'||q||'%' or k.answer ilike '%'||q||'%' or coalesce(k.tags,'') ilike '%'||q||'%'
         or exists (
           select 1 from unnest(toks) t(tok)
            where length(tok) >= 2
              and (lower(k.question) like '%'||t.tok||'%' or lower(k.answer) like '%'||t.tok||'%' or lower(coalesce(k.tags,'')) like '%'||t.tok||'%')
         )
       )
     order by (k.question ilike '%'||q||'%') desc,
              (select count(*) from unnest(toks) t(tok)
                where length(t.tok) >= 2
                  and (lower(k.question) like '%'||t.tok||'%' or lower(k.answer) like '%'||t.tok||'%' or lower(coalesce(k.tags,'')) like '%'||t.tok||'%')) desc,
              k.created_at desc
     limit 20;
end $$;

-- ================= Улучшение подбора технологии =================
create or replace function public.app_tech_recommend(p_token uuid, p_material text, p_feature text)
returns table (recommendation text, note text, matched_material text, matched_feature text)
language plpgsql security definer set search_path = public
as $$
#variable_conflict use_column
declare urole text; ten uuid; mat text; ft text;
begin
  if not public.app_production_allowed(p_token) then raise exception 'Доступ запрещён'; end if;
  select s.urole into urole from public.app_session_user(p_token) s;
  ten := public.app_my_tenant(p_token);
  mat := lower(coalesce(trim(p_material),''));
  ft := lower(coalesce(trim(p_feature),''));
  return query
    select r.recommendation, r.note, r.material, r.feature
    from public.app_tech_rules r
    where (urole='admin' or r.tenant_id = ten or r.tenant_id is null)
      and (coalesce(r.material,'*') in ('*','') or mat = '' or r.material ilike '%'||mat||'%' or mat ilike '%'||lower(r.material)||'%')
      and (coalesce(r.feature,'*') in ('*','') or ft = '' or lower(r.feature) = ft or ft like '%'||lower(r.feature)||'%')
    order by
      (case when coalesce(r.material,'*') in ('*','') then 1 else 0 end) +
      (case when coalesce(r.feature,'*') in ('*','') then 1 else 0 end),
      r.recommendation
    limit 6;
end $$;

