insert into public.app_knowledge (tenant_id, category, question, answer, tags)
select 'aaaaaaaa-0000-0000-0000-000000000001', v.category, v.question, v.answer, v.tags
from (values
  ('Документы','КП, договоры, акты: версии и реестр',
   'Документы (app_doc_list, app_doc_create): КП, договор, техкарта, акт, прочее; версионирование (сохранение новой версии), статусы (черновик → в работе → архив), привязка к заявке и заказчику, сумма. Реестр документов — кнопка «📄 Отчёт PDF». Шаблоны документов — модуль «Шаблоны» (apps/templates). Связи: Заказы, Финансы, Закупки, Сервис (акт/КП).',
   'документы КП договор акт техкарта версии реестр шаблоны')
) as v(category,question,answer,tags)
where not exists (
  select 1 from public.app_knowledge
   where tenant_id = 'aaaaaaaa-0000-0000-0000-000000000001' and question = 'КП, договоры, акты: версии и реестр'
);
