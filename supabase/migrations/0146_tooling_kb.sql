   'Инструмент (app_tool_life_list): тип/материал/покрытие/Ø, ресурс и наработка (мин), число заточек, статусы (в работе/изношен/списан), привязка к оборудованию. Наработка/заточки учитываются (app_tool_wear_add), KPI — app_tool_kpi (всего/изношено/списано/средний износ). Отчёт по инструменту — кнопка «📄 Отчёт PDF». Связи: Производство, Склад (закупка/заточка), ТОиР, Маршруты, Закупки.',
