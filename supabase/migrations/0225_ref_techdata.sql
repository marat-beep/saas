create or replace function public.app_ref_techdata_list(p_token uuid, p_kind text default null, p_q text default null)
returns table (id uuid, kind text, category text, name text, value text, note text)
language plpgsql security definer set search_path = public
as $$
#variable_conflict use_column
declare adm boolean; ten uuid; kk text; qq text;
begin
  if not public.app_production_allowed(p_token) then raise exception 'Доступ запрещён'; end if;
  adm := public.app_is_platform_admin(p_token); ten := public.app_my_tenant(p_token);
  kk := nullif(trim(coalesce(p_kind,'')),''); qq := lower(coalesce(trim(p_q),''));
  return query select t.id, t.kind, t.category, t.name, t.value, t.note
    from public.app_ref_techdata t
    where (t.tenant_id is null or t.tenant_id=ten or adm)
      and (kk is null or t.kind=kk)
      and (qq='' or lower(t.name) like '%'||qq||'%' or lower(coalesce(t.category,'')) like '%'||qq||'%' or lower(coalesce(t.value,'')) like '%'||qq||'%')
    order by t.kind, t.category, t.name;
end $$;

grant execute on function public.app_ref_techdata_list(uuid,text,text) to anon, authenticated;

